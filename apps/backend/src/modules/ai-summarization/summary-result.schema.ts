/**
 * The JSON structure saved to AiAnalysis.result for summarization analyses.
 * This is stored as Prisma Json type — kept as a plain TypeScript interface.
 */
export type SummaryType = 'EXECUTIVE' | 'CITIZEN' | 'LEGAL_OFFICER' | 'AMENDMENT' | 'BILL';

export interface SummaryResult {
  title: string;
  summaryType: SummaryType;
  keyPoints: string[];
  summary: string;
  wordCount: number;
  confidenceScore: number;
  disclaimer: string;
  sources: string[];
}

/**
 * JSON schema object used for building AI prompts that enforce the structure.
 */
export const SUMMARY_RESULT_JSON_SCHEMA: Record<string, unknown> = {
  type: 'object',
  required: [
    'title',
    'summaryType',
    'keyPoints',
    'summary',
    'wordCount',
    'confidenceScore',
    'disclaimer',
    'sources',
  ],
  properties: {
    title: { type: 'string' },
    summaryType: {
      type: 'string',
      enum: ['EXECUTIVE', 'CITIZEN', 'LEGAL_OFFICER', 'AMENDMENT', 'BILL'],
    },
    keyPoints: { type: 'array', items: { type: 'string' } },
    summary: { type: 'string' },
    wordCount: { type: 'integer' },
    confidenceScore: { type: 'number', minimum: 0, maximum: 1 },
    disclaimer: { type: 'string' },
    sources: { type: 'array', items: { type: 'string' } },
  },
};

/**
 * Default disclaimer text appended to every AI-generated summary.
 */
export const DEFAULT_SUMMARY_DISCLAIMER =
  'This summary was generated by AI and is intended as a reference tool only. ' +
  'It does not constitute legal advice. Always refer to the original legislative text ' +
  'and consult qualified legal professionals for authoritative interpretation.';
